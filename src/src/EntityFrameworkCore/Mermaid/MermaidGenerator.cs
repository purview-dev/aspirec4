using System.Globalization;
using System.Text;
using Aspire.Hosting.AspireC4.EntityFrameworkCore.Models;

namespace Aspire.Hosting.AspireC4.EntityFrameworkCore.Mermaid;

/// <summary>
/// Emits a Mermaid <c>erDiagram</c> from an <see cref="EfModel"/>, targeting Mermaid 12.
/// </summary>
/// <remarks>
/// <para>
/// Mermaid is the only supported format that renders inline on GitHub and most wikis, which is the
/// reason it exists here. It is also the lowest fidelity: relationships join <i>entities</i>, not
/// columns, so which column participates survives only as the edge label, and grouping is limited to a
/// single flat <c>subgraph</c> level (11.17+).
/// </para>
/// <para>
/// Cardinality mapping, derived from the foreign key rather than declared by EF:
/// </para>
/// <list type="table">
///   <listheader><term>IsUnique</term><term>IsRequired</term><term>Emitted</term></listheader>
///   <item><term>true</term><term>true</term><term><c>||--||</c> one-to-one, mandatory</term></item>
///   <item><term>true</term><term>false</term><term><c>||--o|</c> one-to-zero-or-one</term></item>
///   <item><term>false</term><term>true</term><term><c>||--|{</c> one-to-one-or-many</term></item>
///   <item><term>false</term><term>false</term><term><c>||--o{</c> one-to-zero-or-many</term></item>
/// </list>
/// <para>
/// The principal side is always <c>||</c>: a foreign key references exactly one principal row. The
/// line style is always identifying (<c>--</c>) because delete behaviour and ownership are runtime EF
/// concepts that static analysis cannot recover, and guessing non-identifying would be misleading.
/// </para>
/// </remarks>
public static class MermaidGenerator
{
	/// <summary>Generates Mermaid <c>erDiagram</c> source from the given model and options.</summary>
	public static string Generate(EfModel model, AspireC4EfDiagramOptions options)
	{
		ArgumentNullException.ThrowIfNull(model);
		ArgumentNullException.ThrowIfNull(options);

		StringBuilder sb = new(512);

		WriteHeader(sb);
		sb.AppendLine("erDiagram");

		var group = options.GroupByContext && model.Contexts.Count > 1 && options.UseSubgraphs;

		foreach (var context in model.Contexts)
		{
			if (group)
			{
				sb.Append("\tsubgraph ").AppendLine(Identifier(context.Name));
			}

			var indent = group ? "\t\t" : "\t";

			foreach (var table in context.Tables)
			{
				WriteEntity(sb, table, indent, options);
			}

			if (group)
			{
				sb.AppendLine("\tend");
			}
		}

		WriteRelationships(sb, model);
		WriteStyles(sb, model, group);

		return sb.ToString();
	}

	static void WriteHeader(StringBuilder sb)
	{
		var now = DateTimeOffset.UtcNow;

		sb.AppendLine("%% =============================================================================");
		sb.Append("%% AUTO-GENERATED by AspireC4 — ")
			.AppendLine(now.ToString("yyyy-MM-dd HH:mm:ss 'UTC'", CultureInfo.InvariantCulture));
		sb.AppendLine("%% Do not edit this file manually. Any changes will be overwritten on the");
		sb.AppendLine("%% next diagram regeneration (on Aspire startup or resource state change).");
		sb.AppendLine("%% See https://github.com/purview-dev/aspirec4 for more information.");
		sb.AppendLine("%% =============================================================================");
	}

	static void WriteEntity(StringBuilder sb, EfTable table, string indent, AspireC4EfDiagramOptions options)
	{
		sb.Append(indent).Append(Identifier(table.Name));

		// An alias keeps the CLR type visible when it differs from the table name.
		var alias = ShortClrName(table.ClrTypeName);

		if (!string.Equals(alias, table.Name, StringComparison.Ordinal))
		{
			sb.Append('[').Append(Quote(alias)).Append(']');
		}

		sb.AppendLine(" {");

		foreach (var column in table.Columns)
		{
			WriteAttribute(sb, column, indent, options);
		}

		sb.Append(indent).AppendLine("}");
	}

	static void WriteAttribute(StringBuilder sb, EfColumn column, string indent, AspireC4EfDiagramOptions options)
	{
		sb.Append(indent).Append('\t').Append(StoreType(column, options)).Append(' ').Append(Identifier(column.Name));

		List<string> keys = [];

		if (column.IsPrimaryKey)
		{
			keys.Add("PK");
		}

		if (column.IsForeignKey)
		{
			keys.Add("FK");
		}

		if (column.IsUnique && !column.IsPrimaryKey)
		{
			keys.Add("UK");
		}

		if (keys.Count > 0)
		{
			sb.Append(' ').Append(string.Join(", ", keys));
		}

		// Mermaid renders a quoted trailing string as the attribute's comment; the value type and the
		// column's own comment share it.
		List<string> notes = [];

		if (EfColumnTypeDisplay.Annotation(column, options) is { } annotation)
		{
			notes.Add(annotation);
		}

		if (!string.IsNullOrWhiteSpace(column.Comment))
		{
			notes.Add(column.Comment);
		}

		if (notes.Count > 0)
		{
			sb.Append(' ').Append(Quote(string.Join(" — ", notes)));
		}

		sb.AppendLine();
	}

	static void WriteRelationships(StringBuilder sb, EfModel model)
	{
		var names = model
			.Contexts.SelectMany(c => c.Tables)
			.Select(t => t.Name)
			.ToHashSet(StringComparer.OrdinalIgnoreCase);

		foreach (var table in model.Contexts.SelectMany(c => c.Tables))
		{
			foreach (var foreignKey in table.ForeignKeys)
			{
				if (!names.Contains(foreignKey.PrincipalTable))
				{
					continue;
				}

				// The label carries the column names, because Mermaid cannot attach an edge to a row.
				var label = foreignKey.NavigationName ?? string.Join(", ", foreignKey.Columns);

				sb.Append('\t')
					.Append(Identifier(foreignKey.PrincipalTable))
					.Append(' ')
					.Append(Cardinality(foreignKey))
					.Append(' ')
					.Append(Identifier(table.Name))
					.Append(" : ")
					.AppendLine(Quote(label));
			}
		}
	}

	/// <summary>See the mapping table on the class remarks.</summary>
	static string Cardinality(EfForeignKey foreignKey) =>
		(foreignKey.IsUnique, foreignKey.IsRequired) switch
		{
			(true, true) => "||--||",
			(true, false) => "||--o|",
			(false, true) => "||--|{",
			(false, false) => "||--o{",
		};

	/// <summary>
	/// Soft fills with saturated strokes, cycled by context so entities are coloured by origin.
	/// </summary>
	/// <remarks>
	/// Mermaid 12 defaults ER diagrams to the <c>redux-color</c> theme, which these override. That is
	/// deliberate: the theme has no concept of which <c>DbContext</c> an entity came from, and showing
	/// that is the point of the grouping.
	/// </remarks>
	static readonly (string Fill, string Stroke)[] ContextPalette =
	[
		("#dbeafe", "#3b82f6"),
		("#dcfce7", "#22c55e"),
		("#fef3c7", "#f59e0b"),
		("#fae8ff", "#a855f7"),
		("#ffe4e6", "#f43f5e"),
		("#ccfbf1", "#14b8a6"),
	];

	/// <summary>
	/// Label colour pinned alongside every context fill.
	/// </summary>
	/// <remarks>
	/// A <c>classDef</c> that sets a fill but not a colour leaves the label to the active Mermaid
	/// theme, which under the dark theme is near-white — illegible on these pale fills. The fills are
	/// fixed whatever the theme, so the text on them has to be fixed too. Dark enough to clear WCAG AA
	/// against the lightest fill in the palette.
	/// </remarks>
	const string ContextLabelColour = "#1f2937";

	static void WriteStyles(StringBuilder sb, EfModel model, bool grouped)
	{
		if (!grouped)
		{
			return;
		}

		// A ':::' assignment with no matching classDef parses but silently does nothing, so the
		// definitions have to be emitted too.
		for (var i = 0; i < model.Contexts.Count; i++)
		{
			var (fill, stroke) = ContextPalette[i % ContextPalette.Length];

			sb.Append("\tclassDef ")
				.Append(Identifier(model.Contexts[i].Name))
				.Append(" fill:")
				.Append(fill)
				.Append(",stroke:")
				.Append(stroke)
				.Append(",color:")
				.AppendLine(ContextLabelColour);
		}

		foreach (var context in model.Contexts)
		{
			foreach (var table in context.Tables)
			{
				sb.Append('\t').Append(Identifier(table.Name)).Append(":::").AppendLine(Identifier(context.Name));
			}
		}
	}

	static string StoreType(EfColumn column, AspireC4EfDiagramOptions options)
	{
		// Mermaid's attribute-type grammar permits letters, digits, hyphens, underscores, parentheses
		// and square brackets — but not commas. decimal(18,2) would fail to parse, so the separator is
		// rewritten rather than the precision dropped.
		var type = EfColumnTypeDisplay.Primary(column, options).Replace(",", "_", StringComparison.Ordinal);

		if (options.ShowNullability && column.IsNullable && !column.IsPrimaryKey)
		{
			type += "?";
		}

		return type;
	}

	/// <summary>Takes the unqualified CLR type name, which is what a reader recognises.</summary>
	static string ShortClrName(string clrTypeName)
	{
		var index = clrTypeName.LastIndexOf('.');

		return index >= 0 && index < clrTypeName.Length - 1 ? clrTypeName[(index + 1)..] : clrTypeName;
	}

	/// <summary>Mermaid identifiers cannot contain spaces; anything else is replaced.</summary>
	internal static string Identifier(string value)
	{
		if (string.IsNullOrEmpty(value))
		{
			return "_";
		}

		StringBuilder sb = new(value.Length);

		foreach (var c in value)
		{
			sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
		}

		var result = sb.ToString();

		return char.IsDigit(result[0]) ? "_" + result : result;
	}

	static string Quote(string value) =>
		$"\"{value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "'", StringComparison.Ordinal)}\"";
}
