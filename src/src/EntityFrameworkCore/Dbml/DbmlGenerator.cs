using System.Globalization;
using System.Text;
using Aspire.Hosting.AspireC4.EntityFrameworkCore.Models;

namespace Aspire.Hosting.AspireC4.EntityFrameworkCore.Dbml;

/// <summary>
/// Emits DBML from an <see cref="EfModel"/>.
/// </summary>
/// <remarks>
/// DBML is the highest-fidelity text projection available: references are column-level, and precision
/// types such as <c>decimal(18,2)</c> are carried verbatim. Output is intended for interchange — for
/// example pasting into dbdiagram.io or converting to SQL — rather than for direct rendering.
/// </remarks>
public static class DbmlGenerator
{
	/// <summary>Generates DBML from the given model and options.</summary>
	public static string Generate(EfModel model, AspireC4EfDiagramOptions options)
	{
		ArgumentNullException.ThrowIfNull(model);
		ArgumentNullException.ThrowIfNull(options);

		StringBuilder sb = new(512);

		WriteHeader(sb, options);

		foreach (var context in model.Contexts)
		{
			foreach (var table in context.Tables)
			{
				WriteTable(sb, context, table, options);
			}
		}

		WriteReferences(sb, model, options);

		return sb.ToString();
	}

	static void WriteHeader(StringBuilder sb, AspireC4EfDiagramOptions options)
	{
		var now = DateTimeOffset.UtcNow;

		sb.AppendLine("// =============================================================================");
		sb.Append("// AUTO-GENERATED by AspireC4 — ")
			.AppendLine(now.ToString("yyyy-MM-dd HH:mm:ss 'UTC'", CultureInfo.InvariantCulture));
		sb.AppendLine("// Do not edit this file manually. Any changes will be overwritten on the");
		sb.AppendLine("// next diagram regeneration (on Aspire startup or resource state change).");
		sb.AppendLine("// See https://github.com/purview-dev/aspirec4 for more information.");
		sb.AppendLine("// =============================================================================");
		sb.AppendLine();

		if (!string.IsNullOrWhiteSpace(options.Title))
		{
			sb.AppendLine("Project aspirec4 {");
			sb.Append("\tNote: ").AppendLine(Quote(options.Title));
			sb.AppendLine("}");
			sb.AppendLine();
		}
	}

	static void WriteTable(StringBuilder sb, EfContext context, EfTable table, AspireC4EfDiagramOptions options)
	{
		sb.Append("Table ").Append(QualifiedName(context, table, options)).AppendLine(" {");

		foreach (var column in table.Columns)
		{
			WriteColumn(sb, column);
		}

		// The owning context is recorded as a note so the grouping survives a round-trip through
		// tools that have no concept of it.
		sb.AppendLine();
		sb.Append("\tNote: ").AppendLine(Quote($"{context.Name} ({table.ClrTypeName})"));
		sb.AppendLine("}");
		sb.AppendLine();
	}

	static void WriteColumn(StringBuilder sb, EfColumn column)
	{
		sb.Append('\t').Append(Identifier(column.Name)).Append(' ').Append(StoreType(column));

		List<string> settings = [];

		if (column.IsPrimaryKey)
		{
			settings.Add("pk");
		}

		// A primary key is already unique; repeating it adds noise to every row.
		if (column.IsUnique && !column.IsPrimaryKey)
		{
			settings.Add("unique");
		}

		if (!column.IsNullable && !column.IsPrimaryKey)
		{
			settings.Add("not null");
		}

		if (settings.Count > 0)
		{
			sb.Append(" [").Append(string.Join(", ", settings)).Append(']');
		}

		sb.AppendLine();
	}

	/// <summary>
	/// Writes relationships as standalone <c>Ref</c> blocks rather than inline column settings, so a
	/// composite foreign key stays a single reference instead of being split across columns.
	/// </summary>
	static void WriteReferences(StringBuilder sb, EfModel model, AspireC4EfDiagramOptions options)
	{
		Dictionary<string, (EfContext Context, EfTable Table)> byName = new(StringComparer.OrdinalIgnoreCase);

		foreach (var context in model.Contexts)
		{
			foreach (var table in context.Tables)
			{
				byName[table.Name] = (context, table);
			}
		}

		foreach (var context in model.Contexts)
		{
			foreach (var table in context.Tables)
			{
				foreach (var foreignKey in table.ForeignKeys)
				{
					if (!byName.TryGetValue(foreignKey.PrincipalTable, out var principal))
					{
						continue;
					}

					// '-' is one-to-one, '>' is many-to-one. The dependent side is written first.
					var cardinality = foreignKey.IsUnique ? '-' : '>';

					sb.Append("Ref: ")
						.Append(QualifiedName(context, table, options))
						.Append('.')
						.Append(ColumnList(foreignKey.Columns))
						.Append(' ')
						.Append(cardinality)
						.Append(' ')
						.Append(QualifiedName(principal.Context, principal.Table, options))
						.Append('.')
						.AppendLine(ColumnList(foreignKey.PrincipalColumns));
				}
			}
		}
	}

	/// <summary>Renders a single column, or a composite key as a parenthesised list.</summary>
	static string ColumnList(IReadOnlyList<string> columns) =>
		columns.Count == 1 ? Identifier(columns[0]) : $"({string.Join(", ", columns.Select(Identifier))})";

	/// <summary>
	/// Qualifies a table with its schema when one is known, since DBML models schemas natively.
	/// </summary>
	static string QualifiedName(EfContext context, EfTable table, AspireC4EfDiagramOptions options)
	{
		var schema = table.Schema ?? context.DefaultSchema;

		return options.GroupBySchema && !string.IsNullOrWhiteSpace(schema)
			? $"{Identifier(schema)}.{Identifier(table.Name)}"
			: Identifier(table.Name);
	}

	static string StoreType(EfColumn column) =>
		column.MaxLength is > 0 && !column.StoreType.Contains('(', StringComparison.Ordinal)
			? $"{column.StoreType}({column.MaxLength.Value.ToString(CultureInfo.InvariantCulture)})"
			: column.StoreType;

	/// <summary>Quotes an identifier only when it is not a bare word, as DBML allows both forms.</summary>
	internal static string Identifier(string value)
	{
		if (string.IsNullOrEmpty(value))
		{
			return "\"\"";
		}

		foreach (var c in value)
		{
			if (!char.IsLetterOrDigit(c) && c != '_')
			{
				return Quote(value);
			}
		}

		return char.IsDigit(value[0]) ? Quote(value) : value;
	}

	static string Quote(string value) =>
		$"\"{value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)}\"";
}
