using System.Globalization;
using System.Text;
using Aspire.Hosting.AspireC4.EntityFrameworkCore.D2.Models;

namespace Aspire.Hosting.AspireC4.EntityFrameworkCore.D2.Generators;

/// <summary>
/// Generates a d2 (<c>.d2</c>) string from a <see cref="D2Model"/>, using <c>shape: sql_table</c>
/// for each table and column-level edges for foreign keys.
/// </summary>
public static class D2DSLGenerator
{
	/// <summary>
	/// d2 keywords that would be reinterpreted as configuration if they appeared as a bare row key
	/// inside a <c>sql_table</c> block. A column with one of these names is quoted.
	/// </summary>
	static readonly HashSet<string> ReservedKeywords =
	[
		with(StringComparer.OrdinalIgnoreCase),
		"shape",
		"label",
		"icon",
		"constraint",
		"tooltip",
		"link",
		"near",
		"width",
		"height",
		"direction",
		"style",
		"class",
		"classes",
		"vars",
		"layers",
		"scenarios",
		"steps",
		"grid-rows",
		"grid-columns",
		"grid-gap",
		"vertical-gap",
		"horizontal-gap",
		"source-arrowhead",
		"target-arrowhead",
	];

	/// <summary>Generates a d2 DSL string from the given model and options.</summary>
	public static string Generate(D2Model model, AspireC4EfDiagramOptions options)
	{
		ArgumentNullException.ThrowIfNull(model);
		ArgumentNullException.ThrowIfNull(options);

		StringBuilder sb = new(512);

		WriteHeader(sb);
		WriteConfig(sb, options);
		WriteTables(sb, model);
		WriteEdges(sb, model);

		return sb.ToString();
	}

	static void WriteHeader(StringBuilder sb)
	{
		var now = DateTimeOffset.UtcNow;
		sb.AppendLine("# =============================================================================");
		sb.Append("# AUTO-GENERATED by AspireC4 — ")
			.AppendLine(now.ToString("yyyy-MM-dd HH:mm:ss 'UTC'", CultureInfo.InvariantCulture));
		sb.AppendLine("# Do not edit this file manually. Any changes will be overwritten on the");
		sb.AppendLine("# next diagram regeneration (on Aspire startup or resource state change).");
		sb.AppendLine("# See https://github.com/purview-dev/aspirec4 for more information.");
		sb.AppendLine("# =============================================================================");
		sb.AppendLine();
	}

	static void WriteConfig(StringBuilder sb, AspireC4EfDiagramOptions options)
	{
		// Pin the layout engine in the file itself so the diagram renders correctly regardless of
		// how the d2 CLI happens to be invoked. dagre cannot target sql_table rows.
		sb.AppendLine("vars: {");
		sb.AppendLine("\td2-config: {");
		sb.Append("\t\tlayout-engine: ").AppendLine(ToEngineName(options.LayoutEngine));
		sb.AppendLine("\t}");
		sb.AppendLine("}");
		sb.AppendLine();

		if (!string.IsNullOrWhiteSpace(options.Title))
		{
			sb.Append("title: |md # ").Append(options.Title).AppendLine(" | { near: top-center }");
			sb.AppendLine();
		}
	}

	static void WriteTables(StringBuilder sb, D2Model model)
	{
		// Tables are grouped by container so each container block is emitted once, with its
		// tables nested inside it. Ungrouped tables are written at the top level.
		var grouped = model.Tables.GroupBy(t => t.Container, StringComparer.Ordinal);

		foreach (var group in grouped.OrderBy(g => g.Key ?? string.Empty, StringComparer.Ordinal))
		{
			var indent = string.Empty;

			if (!string.IsNullOrWhiteSpace(group.Key))
			{
				sb.Append(group.Key).AppendLine(": {");
				indent = "\t";
			}

			foreach (var table in group)
			{
				WriteTable(sb, table, indent);
			}

			if (!string.IsNullOrWhiteSpace(group.Key))
			{
				sb.AppendLine("}");
				sb.AppendLine();
			}
		}
	}

	static void WriteTable(StringBuilder sb, D2Table table, string indent)
	{
		sb.Append(indent).Append(table.Id).AppendLine(": {");
		sb.Append(indent).AppendLine("\tshape: sql_table");

		if (!string.Equals(table.Label, table.Id, StringComparison.Ordinal))
		{
			sb.Append(indent).Append("\tlabel: ").AppendLine(Quote(table.Label));
		}

		foreach (var column in table.Columns)
		{
			WriteColumn(sb, column, indent);
		}

		sb.Append(indent).AppendLine("}");
		sb.AppendLine();
	}

	static void WriteColumn(StringBuilder sb, D2Column column, string indent)
	{
		sb.Append(indent).Append('\t').Append(EscapeKey(column.Name)).Append(": ").Append(column.Type);

		if (column.Constraints.Count > 0)
		{
			var names = column.Constraints.Select(ToConstraintName);

			sb.Append(" {constraint: ")
				.Append(column.Constraints.Count == 1 ? names.First() : $"[{string.Join("; ", names)}]")
				.Append('}');
		}

		sb.AppendLine();
	}

	static void WriteEdges(StringBuilder sb, D2Model model)
	{
		if (model.Edges.Count == 0)
		{
			return;
		}

		foreach (var edge in model.Edges)
		{
			sb.Append(edge.SourceTable)
				.Append('.')
				.Append(EscapeKey(edge.SourceColumn))
				.Append(" -> ")
				.Append(edge.TargetTable)
				.Append('.')
				.Append(EscapeKey(edge.TargetColumn));

			if (!string.IsNullOrWhiteSpace(edge.Label))
			{
				sb.Append(": ").Append(Quote(edge.Label));
			}

			sb.AppendLine();
		}
	}

	static string ToEngineName(D2LayoutEngine engine) =>
		engine switch
		{
			D2LayoutEngine.Dagre => "dagre",
			D2LayoutEngine.Elk => "elk",
			D2LayoutEngine.Tala => "tala",
			_ => "elk",
		};

	static string ToConstraintName(D2Constraint constraint) =>
		constraint switch
		{
			D2Constraint.PrimaryKey => "primary_key",
			D2Constraint.ForeignKey => "foreign_key",
			D2Constraint.Unique => "unique",
			_ => "unique",
		};

	/// <summary>
	/// Quotes a key when it is a d2 keyword or contains characters d2 would not accept bare, so that
	/// a column legitimately named <c>label</c> or <c>shape</c> does not become table configuration.
	/// </summary>
	internal static string EscapeKey(string key) =>
		ReservedKeywords.Contains(key) || !IsBareIdentifier(key) ? Quote(key) : key;

	static bool IsBareIdentifier(string value)
	{
		if (string.IsNullOrEmpty(value))
		{
			return false;
		}

		foreach (var c in value)
		{
			if (!char.IsLetterOrDigit(c) && c != '_')
			{
				return false;
			}
		}

		return true;
	}

	/// <summary>Wraps a value in double quotes, escaping any embedded quotes or backslashes.</summary>
	internal static string Quote(string value) =>
		$"\"{value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)}\"";

	/// <summary>
	/// Converts an arbitrary name into a bare d2 identifier. Used for table identifiers so that edges
	/// can reference them without quoting; the original name is preserved as the table's label.
	/// </summary>
	internal static string Sanitize(string value)
	{
		if (string.IsNullOrEmpty(value))
		{
			return "_";
		}

		StringBuilder sb = new(value.Length);

		foreach (var c in value)
		{
			sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
		}

		var result = sb.ToString();

		// A leading digit is not a valid bare identifier, and a reserved keyword would be
		// reinterpreted as configuration.
		return char.IsDigit(result[0]) || ReservedKeywords.Contains(result) ? "_" + result : result;
	}
}
