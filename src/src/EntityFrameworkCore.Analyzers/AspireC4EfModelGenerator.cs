using System.Collections.Immutable;
using Aspire.Hosting.AspireC4.EntityFrameworkCore.Analyzers.Analysis;
using Aspire.Hosting.AspireC4.EntityFrameworkCore.Analyzers.Helpers;
using Aspire.Hosting.AspireC4.EntityFrameworkCore.Analyzers.Models;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Aspire.Hosting.AspireC4.EntityFrameworkCore.Analyzers;

/// <summary>
/// Analyses the <c>DbContext</c> types in the compilation and emits an assembly-level descriptor the
/// AspireC4 AppHost reads back to draw a d2 ER diagram.
/// </summary>
/// <remarks>
/// The descriptor is emitted as <c>[assembly: AspireC4EfModel("...")]</c> rather than written to disk,
/// so the generator stays pure and deterministic. The AppHost reads the attribute straight out of the
/// built assembly's metadata, without loading or executing it.
/// </remarks>
[Generator]
public sealed class AspireC4EfModelGenerator : IIncrementalGenerator
{
	internal const string AttributeName = "AspireC4EfModelAttribute";

	internal const string AttributeSource = """
		// <auto-generated/>
		#nullable enable

		namespace Aspire.Hosting.AspireC4.EntityFrameworkCore;

		/// <summary>
		/// Carries the AspireC4 Entity Framework Core model descriptor for this assembly.
		/// Emitted by the AspireC4 source generator; do not apply this attribute by hand.
		/// </summary>
		[global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = false)]
		[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
		internal sealed class AspireC4EfModelAttribute : global::System.Attribute
		{
			public AspireC4EfModelAttribute(string descriptor) => Descriptor = descriptor;

			/// <summary>The JSON model descriptor.</summary>
			public string Descriptor { get; }
		}
		""";

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(ctx => ctx.AddSource($"{AttributeName}.g.cs", AttributeSource));

		// ForAttributeWithMetadataName cannot be used here: contexts are identified by deriving from
		// DbContext, not by carrying an attribute. The predicate is kept cheap and purely syntactic.
#pragma warning disable PSGFR11
		var contexts = context
			.SyntaxProvider.CreateSyntaxProvider(
				static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
				static (ctx, _) => Transform(ctx)
			)
			.Where(static result => result is not null)
			.Select(static (result, _) => result!)
			.Collect();
#pragma warning restore PSGFR11

		context.RegisterSourceOutput(contexts, static (ctx, results) => Emit(ctx, results));
	}

	static ContextDescriptor? Transform(GeneratorSyntaxContext ctx)
	{
		if (
			ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) is not INamedTypeSymbol symbol
			|| !DerivesFromDbContext(symbol)
		)
		{
			return null;
		}

		var result = EfModelAnalyser.Analyse(symbol, ctx.SemanticModel);

		return new ContextDescriptor(
			WriteContextJson(result),
			new EquatableArray<EfDiagnosticInfo>([
				.. result.Diagnostics.Select(d => new EfDiagnosticInfo(d.Descriptor.Id, d.Argument, null, 0, 0)),
			])
		);
	}

	static bool DerivesFromDbContext(INamedTypeSymbol symbol)
	{
		for (var current = symbol.BaseType; current is not null; current = current.BaseType)
		{
			if (current.ToDisplayString() == EfTypes.DbContext)
			{
				return true;
			}
		}

		return false;
	}

	static void Emit(SourceProductionContext ctx, ImmutableArray<ContextDescriptor> descriptors)
	{
		foreach (var diagnostic in descriptors.SelectMany(d => d.Diagnostics))
		{
			var descriptor = ResolveDescriptor(diagnostic.Id);

			if (descriptor is not null)
			{
				ctx.ReportDiagnostic(Diagnostic.Create(descriptor, Location.None, diagnostic.Argument));
			}
		}

		if (descriptors.Length == 0)
		{
			return;
		}

		JsonWriter json = new();

		json.StartObject().Number("schemaVersion", 1);
		json.Array("contexts", descriptors, static (writer, descriptor) => writer.Raw(descriptor.Json));
		json.EndObject();

		var source = $$"""
			// <auto-generated/>
			#nullable enable

			[assembly: global::Aspire.Hosting.AspireC4.EntityFrameworkCore.AspireC4EfModelAttribute(
				{{Literal(json.ToString())}}
			)]
			""";

		ctx.AddSource("AspireC4EfModel.g.cs", source);
	}

	static DiagnosticDescriptor? ResolveDescriptor(string id) =>
		id switch
		{
			"ASPIREC4008" => DiagnosticLibrary.NoEntityTypesDiscovered,
			"ASPIREC4009" => DiagnosticLibrary.NoPrimaryKeyDiscovered,
			"ASPIREC4010" => DiagnosticLibrary.UninterpretableConfiguration,
			_ => null,
		};

	static string WriteContextJson(EfModelAnalyser.Result result)
	{
		JsonWriter json = new();

		json.StartObject()
			.Text("name", result.Name)
			.Text("typeName", result.TypeName)
			.Text("defaultSchema", result.DefaultSchema);

		json.Array(
			"tables",
			result.Tables,
			static (writer, table) =>
			{
				writer
					.StartObject()
					.Text("name", table.Name)
					.Text("clrTypeName", table.ClrTypeName)
					.Text("schema", table.Schema)
					.Bool("isJoinEntity", table.IsJoinEntity);

				writer.Array(
					"columns",
					table.Columns,
					static (w, column) =>
						w.StartObject()
							.Text("name", column.Name)
							.Text("storeType", column.StoreType)
							.Text("clrTypeName", column.ClrTypeName)
							.Bool("isNullable", column.IsNullable)
							.Bool("isPrimaryKey", column.IsPrimaryKey)
							.Bool("isUnique", column.IsUnique)
							.Bool("isForeignKey", column.IsForeignKey)
							.Number("maxLength", column.MaxLength)
							.Text("comment", column.Comment)
							.EndObject()
				);

				writer.Array(
					"foreignKeys",
					table.ForeignKeys,
					static (w, foreignKey) =>
					{
						w.StartObject().Text("principalTable", foreignKey.PrincipalEntity);
						w.Array("columns", foreignKey.Columns, static (a, c) => a.Value(c));
						w.Array("principalColumns", foreignKey.PrincipalColumns, static (a, c) => a.Value(c));
						w.Text("navigationName", foreignKey.NavigationName)
							.Bool("isUnique", foreignKey.IsUnique)
							.Bool("isRequired", foreignKey.IsRequired)
							.EndObject();
					}
				);

				writer.EndObject();
			}
		);

		return json.EndObject().ToString();
	}

	/// <summary>Renders a C# string literal for the descriptor.</summary>
	static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

	/// <summary>A single analysed context: its JSON fragment plus any diagnostics raised while analysing it.</summary>
	internal sealed record ContextDescriptor(string Json, EquatableArray<EfDiagnosticInfo> Diagnostics);
}
