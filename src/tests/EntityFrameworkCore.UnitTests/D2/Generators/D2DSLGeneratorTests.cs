using Aspire.Hosting.AspireC4.EntityFrameworkCore.D2.Models;

namespace Aspire.Hosting.AspireC4.EntityFrameworkCore.D2.Generators;

public sealed class D2DSLGeneratorTests
{
	// Helpers

	static AspireC4EfDiagramOptions CreateOptions(
		string? title = null,
		D2LayoutEngine layoutEngine = D2LayoutEngine.Elk
	) => new() { Title = title, LayoutEngine = layoutEngine };

	static D2Column CreateColumn(
		string name = "id",
		string type = "int",
		IReadOnlyList<D2Constraint>? constraints = null
	) =>
		new()
		{
			Name = name,
			Type = type,
			Constraints = constraints ?? [],
		};

	static D2Table CreateTable(
		string id = "users",
		string? label = null,
		string? container = null,
		IReadOnlyList<D2Column>? columns = null
	) =>
		new()
		{
			Id = id,
			Label = label ?? id,
			Container = container,
			Columns = columns ?? [CreateColumn()],
		};

	static D2Model CreateModel(IReadOnlyList<D2Table>? tables = null, IReadOnlyList<D2Edge>? edges = null) =>
		new() { Tables = tables ?? [CreateTable()], Edges = edges ?? [] };

	// Tests

	[Test]
	public async Task Generate_EmptyModel_ProducesConfigBlock()
	{
		// Arrange
		var options = CreateOptions();

		// Act
		var dsl = D2DSLGenerator.Generate(D2Model.Empty, options);

		// Assert
		await Assert.That(dsl).Contains("vars: {");
		await Assert.That(dsl).Contains("d2-config: {");
		await Assert.That(dsl).Contains("layout-engine: elk");
	}

	[Test]
	public async Task Generate_AlwaysEmitsAutoGeneratedHeader()
	{
		// Arrange
		var options = CreateOptions();

		// Act
		var dsl = D2DSLGenerator.Generate(D2Model.Empty, options);

		// Assert
		await Assert.That(dsl).StartsWith("#");
		await Assert.That(dsl).Contains("AUTO-GENERATED by AspireC4");
		await Assert.That(dsl).Contains("Do not edit this file manually");
	}

	[Test]
	public async Task Generate_Table_EmitsSqlTableShape()
	{
		// Arrange
		var model = CreateModel([CreateTable(id: "users")]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("users: {");
		await Assert.That(dsl).Contains("shape: sql_table");
	}

	[Test]
	public async Task Generate_TableLabelDifferingFromId_EmitsLabel()
	{
		// Arrange
		var model = CreateModel([CreateTable(id: "order_items", label: "Order Items")]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("label: \"Order Items\"");
	}

	[Test]
	public async Task Generate_TableLabelMatchingId_OmitsLabel()
	{
		// Arrange
		var model = CreateModel([CreateTable(id: "users", label: "users")]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).DoesNotContain("label:");
	}

	[Test]
	public async Task Generate_SingleConstraint_EmitsScalarSyntax()
	{
		// Arrange
		var column = CreateColumn("id", "int", [D2Constraint.PrimaryKey]);
		var model = CreateModel([CreateTable(columns: [column])]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("id: int {constraint: primary_key}");
	}

	[Test]
	public async Task Generate_MultipleConstraints_EmitsArraySyntax()
	{
		// Arrange
		var column = CreateColumn("code", "varchar", [D2Constraint.ForeignKey, D2Constraint.Unique]);
		var model = CreateModel([CreateTable(columns: [column])]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("code: varchar {constraint: [foreign_key; unique]}");
	}

	[Test]
	public async Task Generate_ColumnNamedAfterReservedKeyword_IsQuoted()
	{
		// A column legitimately named "label" would otherwise be parsed as the table's label.
		// Arrange
		var model = CreateModel([CreateTable(columns: [CreateColumn("label", "varchar")])]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("\"label\": varchar");
	}

	[Test]
	public async Task Generate_ColumnWithNonIdentifierCharacters_IsQuoted()
	{
		// Arrange
		var model = CreateModel([CreateTable(columns: [CreateColumn("created at", "timestamp")])]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("\"created at\": timestamp");
	}

	[Test]
	public async Task Generate_Edge_EmitsColumnLevelEdge()
	{
		// Arrange
		D2Edge edge = new()
		{
			SourceTable = "orders",
			SourceColumn = "user_id",
			TargetTable = "users",
			TargetColumn = "id",
		};
		var model = CreateModel([CreateTable(id: "orders"), CreateTable(id: "users")], [edge]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("orders.user_id -> users.id");
	}

	[Test]
	public async Task Generate_EdgeWithLabel_AppendsQuotedLabel()
	{
		// Arrange
		D2Edge edge = new()
		{
			SourceTable = "orders",
			SourceColumn = "user_id",
			TargetTable = "users",
			TargetColumn = "id",
			Label = "PlacedBy",
		};
		var model = CreateModel([CreateTable(id: "orders")], [edge]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("orders.user_id -> users.id: \"PlacedBy\"");
	}

	[Test]
	public async Task Generate_TableWithContainer_NestsInsideContainerBlock()
	{
		// Arrange
		var model = CreateModel([CreateTable(id: "orders", container: "sales")]);

		// Act
		var dsl = D2DSLGenerator.Generate(model, CreateOptions());

		// Assert
		await Assert.That(dsl).Contains("sales: {");
		await Assert.That(dsl).Contains("\torders: {");
	}

	[Test]
	[Arguments(D2LayoutEngine.Dagre, "dagre")]
	[Arguments(D2LayoutEngine.Elk, "elk")]
	[Arguments(D2LayoutEngine.Tala, "tala")]
	public async Task Generate_LayoutEngine_IsPinnedInConfig(D2LayoutEngine engine, string expected)
	{
		// Arrange
		var options = CreateOptions(layoutEngine: engine);

		// Act
		var dsl = D2DSLGenerator.Generate(D2Model.Empty, options);

		// Assert
		await Assert.That(dsl).Contains($"layout-engine: {expected}");
	}

	[Test]
	public async Task Generate_Title_EmitsTitleBlock()
	{
		// Arrange
		var options = CreateOptions(title: "Orders Schema");

		// Act
		var dsl = D2DSLGenerator.Generate(D2Model.Empty, options);

		// Assert
		await Assert.That(dsl).Contains("Orders Schema");
	}

	[Test]
	public async Task Generate_NullModel_Throws()
	{
		// Arrange
		var options = CreateOptions();

		// Act & Assert
		await Assert.That(() => D2DSLGenerator.Generate(null!, options)).Throws<ArgumentNullException>();
	}

	[Test]
	public async Task Sanitize_NameWithSeparators_ProducesBareIdentifier()
	{
		// Arrange
		const string Value = "Order-Items.2024";

		// Act
		var result = D2DSLGenerator.Sanitize(Value);

		// Assert
		await Assert.That(result).IsEqualTo("Order_Items_2024");
	}

	[Test]
	public async Task Sanitize_NameStartingWithDigit_IsPrefixed()
	{
		// Arrange
		const string Value = "2024_orders";

		// Act
		var result = D2DSLGenerator.Sanitize(Value);

		// Assert
		await Assert.That(result).IsEqualTo("_2024_orders");
	}

	[Test]
	public async Task Sanitize_ReservedKeyword_IsPrefixed()
	{
		// Arrange
		const string Value = "style";

		// Act
		var result = D2DSLGenerator.Sanitize(Value);

		// Assert
		await Assert.That(result).IsEqualTo("_style");
	}
}
